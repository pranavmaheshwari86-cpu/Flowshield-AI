class ShelterIngestionService:
    """
    Automates source discovery, coordinate validation, deduplication,
    and database population for verified disaster evacuation facilities.
    """

    @staticmethod
    def validate_coordinates(lat: float, lon: float, district: str) -> Tuple[bool, str]:
        """Validates coordinate ranges and district bounding boxes."""
        if not (-90.0 <= lat <= 90.0) or not (-180.0 <= lon <= 180.0):
            return False, f"Invalid WGS84 coordinate: ({lat}, {lon})"

        bounds = DISTRICT_BOUNDS.get(district)
        if bounds:
            min_lat, max_lat = bounds["lat"]
            min_lon, max_lon = bounds["lon"]
            if not (min_lat <= lat <= max_lat and min_lon <= lon <= max_lon):
                return False, (
                    f"Coordinates ({lat}, {lon}) fall outside bounding box for district '{district}' "
                    f"[{min_lat}-{max_lat}N, {min_lon}-{max_lon}E]"
                )

        return True, "Valid"

    @staticmethod
    def normalize_name(name: str) -> str:
        """Normalizes name for deduplication."""
        stop_words = {"government", "govt", "govt.", "inter", "college", "school", "camp", "shelter", "complex", "the", "center", "centre"}
        tokens = name.lower().replace("-", " ").replace(".", " ").replace("/", " ").split()
        filtered = [t for t in tokens if t not in stop_words and len(t) > 1]
        return " ".join(sorted(filtered))

    @classmethod
    def is_duplicate(cls, shelter_a: Dict[str, Any], shelter_b: Dict[str, Any], distance_thresh_km: float = 0.15) -> bool:
        """
        Deduplication logic:
        Checks if two records are within 150m and have matching normalized names.
        """
        dist = haversine_distance_km(
            shelter_a["latitude"], shelter_a["longitude"],
            shelter_b["latitude"], shelter_b["longitude"]
        )
        if dist > distance_thresh_km:
            return False

        norm_a = cls.normalize_name(shelter_a["name"])
        norm_b = cls.normalize_name(shelter_b["name"])
        if norm_a == norm_b or norm_a in norm_b or norm_b in norm_a:
            return True

        return False

    @classmethod
    def run_ingestion_and_validation(cls, db: Session) -> Dict[str, Any]:
        """
        Executes full ingestion, validation, and deduplication pipeline.
        Returns detailed validation audit report.
        """
        report: Dict[str, Any] = {
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "total_candidates": len(AUTHORITATIVE_SHELTERS_DATASET),
            "valid_records": 0,
            "invalid_records": 0,
            "duplicates_merged": 0,
            "districts_covered": list(DISTRICT_BOUNDS.keys()),
            "states_covered": ["Uttarakhand", "Himachal Pradesh"],
            "verification_breakdown": {"VERIFIED": 0, "PARTIALLY_VERIFIED": 0, "UNVERIFIED": 0, "STALE": 0, "INACTIVE": 0},
            "confidence_tiers": {"HIGH (>=85)": 0, "MEDIUM (70-84)": 0, "LOW (<70)": 0},
            "errors": [],
        }

        # 1. Initialize or update model coverage registry
        for cov in INITIAL_MODEL_COVERAGE:
            existing = db.query(ModelCoverage).filter(
                ModelCoverage.state == cov["state"],
                ModelCoverage.district == cov["district"]
            ).first()
            if not existing:
                record = ModelCoverage(
                    state=cov["state"],
                    district=cov["district"],
                    is_supported=cov["is_supported"],
                    has_training_data=cov["has_training_data"],
                    has_prediction=cov["has_prediction"],
                    has_shelter_data=cov["has_shelter_data"],
                    has_route_data=cov["has_route_data"],
                    description=cov.get("description"),
                    last_updated=datetime.now(timezone.utc),
                )
                db.add(record)
            else:
                existing.has_shelter_data = True
                existing.last_updated = datetime.now(timezone.utc)
        db.commit()

        # 2. Ingest and Validate Authoritative Shelters
        accepted_records: List[Dict[str, Any]] = []

        for candidate in AUTHORITATIVE_SHELTERS_DATASET:
            # Validate coordinates
            is_valid, reason = cls.validate_coordinates(
                candidate["latitude"], candidate["longitude"], candidate["district"]
            )
            if not is_valid:
                report["invalid_records"] += 1
                report["errors"].append({"id": candidate["id"], "name": candidate["name"], "reason": reason})
                continue

            # Check duplicate against already accepted records in batch
            dup_found = False
            for accepted in accepted_records:
                if cls.is_duplicate(candidate, accepted):
                    dup_found = True
                    report["duplicates_merged"] += 1
                    logger.info(f"Deduplicated '{candidate['name']}' with '{accepted['name']}'")
                    break

            if dup_found:
                continue

            accepted_records.append(candidate)
            report["valid_records"] += 1
            report["verification_breakdown"][candidate.get("verification_status", "VERIFIED")] = (
                report["verification_breakdown"].get(candidate.get("verification_status", "VERIFIED"), 0) + 1
            )
            score = candidate.get("confidence_score", 85)
            if score >= 85:
                report["confidence_tiers"]["HIGH (>=85)"] += 1
            elif score >= 70:
                report["confidence_tiers"]["MEDIUM (70-84)"] += 1
            else:
                report["confidence_tiers"]["LOW (<70)"] += 1

            # Upsert into database
            existing_db = db.query(Shelter).filter(Shelter.id == candidate["id"]).first()
            # Also search by exact coordinates within 50m
            if not existing_db:
                existing_by_coord = db.query(Shelter).filter(
                    Shelter.latitude.between(candidate["latitude"] - 0.0005, candidate["latitude"] + 0.0005),
                    Shelter.longitude.between(candidate["longitude"] - 0.0005, candidate["longitude"] + 0.0005),
                ).first()
                if existing_by_coord:
                    existing_db = existing_by_coord

            if existing_db:
                # Update with verified metadata
                for k, v in candidate.items():
                    if hasattr(existing_db, k) and k != "id":
                        setattr(existing_db, k, v)
                existing_db.geometry = {"type": "Point", "coordinates": [candidate["longitude"], candidate["latitude"]]}
                existing_db.data_last_updated = datetime.now(timezone.utc)
            else:
                new_shelter = Shelter(
                    **candidate,
                    geometry={"type": "Point", "coordinates": [candidate["longitude"], candidate["latitude"]]},
                    data_last_updated=datetime.now(timezone.utc),
                )
                db.add(new_shelter)

        db.commit()
        logger.info(f"Ingestion complete. {report['valid_records']} verified records loaded into database.")
        return report


shelter_ingestion_service = ShelterIngestionService()
